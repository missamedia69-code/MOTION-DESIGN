"""Final 59.000 s mux for 'Ton envie fait le programme'.

From repo root: python3 projects/missa-tv-360-portail/mix.py
Inputs: .cache/rendus/missa-tv-360-portail-editorial-silent.mp4,
        .cache/vo59-editorial/{s1,s2,s3a,s3b,s4a,s4b,s4c,s5,s6}.mp3,
        .cache/portail-audio/{music,sfx-bed}.wav (generated by sound.py).
Output: livrables/missa-tv-360-portail.mp4 — supersedes the old artistic direction.
No voice clip is sped up, cut, or forced into an overlapping section.
"""
from pathlib import Path
import subprocess
import sys

repo=Path(__file__).resolve().parents[2]
video=repo/'.cache/rendus/missa-tv-360-portail-editorial-silent.mp4'
stems=('s1','s2','s3a','s3b','s4a','s4b','s4c','s5','s6')
starts=(300,6480,16280,22550,29130,35230,40640,46280,53280)
voices=[repo/f'.cache/vo59-editorial/{stem}.mp3' for stem in stems]
music=repo/'.cache/portail-audio/music.wav'
sfx=repo/'.cache/portail-audio/sfx-bed.wav'
out=repo/'livrables/missa-tv-360-portail.mp4'
missing=[str(p.relative_to(repo)) for p in (video,*voices,music,sfx) if not p.exists()]
if missing:
    sys.exit('Médias absents (préparer les prises de voix, rendre l’image, exécuter sound.py) :\n'+'\n'.join(missing))

audio=[]
for i,ms in enumerate(starts,1):
    audio.append(f'[{i}:a]highpass=f=77,volume=1.04,adelay={ms}|{ms},'
                 f'aformat=channel_layouts=stereo[v{i}]')
audio.append('[10:a]volume=1.13[m]')
audio.append('[11:a]volume=.71[e]')
audio.append(''.join(f'[v{i}]' for i in range(1,10))+
             '[m][e]amix=inputs=11:normalize=0,volume=1.28,'+
             'alimiter=limit=.72:attack=5:release=80:level=0,'+
             'apad,afade=t=out:st=58.72:d=0.28,atrim=0:59,asetpts=PTS-STARTPTS[aout]')
cmd=['ffmpeg','-hide_banner','-loglevel','error','-y']
for file in [video,*voices,music,sfx]:
    cmd.extend(['-i',str(file)])
cmd.extend(['-filter_complex',';'.join(audio),'-map','0:v:0','-map','[aout]',
            '-c:v','copy','-c:a','aac','-b:a','192k','-ar','44100','-ac','2',
            '-movflags','+faststart','-metadata','title=Missa TV 360 — Ton envie fait le programme',
            '-metadata','comment=Portrait · 59 s · 6 chapitres · box NET',
            '-t','59',str(out)])
out.parent.mkdir(parents=True,exist_ok=True)
print('Mixage du nouveau master 59 s :',out,flush=True)
subprocess.run(cmd,check=True)
print('OK —',round(out.stat().st_size/1024/1024,1),'Mo')
